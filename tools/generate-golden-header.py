"""Development-only generator. Not required for C++ build or EXE runtime."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
data = json.loads((root / 'tests/golden_cases.json').read_text(encoding='utf8'))
profiles = {'gentle':'Gentle','smart':'Smart','deep':'Deep'}

def wide(s):
    # Produce a C++ wide string literal using JSON's portable escapes.
    return 'L' + json.dumps(s, ensure_ascii=False)

rows = []
for case in data:
    rows.append('{' + json.dumps(case['id']) + ', ' + wide(case['input']) + ', Profile::' +
                profiles[case['profile']] + ', ' + wide(case['expected']) + ', ' +
                ('true' if case['protected_structure'] else 'false') + '},')
(root / 'tests/golden_cases.inc').write_text('// Generated by tools/generate-golden-header.py; do not hand-edit.\n' +
                                            '\n'.join(rows) + '\n', encoding='utf8')
print('Generated',len(rows),'C++ golden cases')
