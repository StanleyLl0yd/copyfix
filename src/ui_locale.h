inline constexpr bool IsValid(DWORD value) noexcept { return value<=2; }
inline Language Effective(Language selected) noexcept {
    if (selected != Language::System) return selected;
    return PRIMARYLANGID(GetUserDefaultUILanguage())==LANG_RUSSIAN
        ? Language::Russian : Language::English;
}
inline const wchar_t* Get(Text text,Language selected) noexcept {
    const auto index=static_cast<std::size_t>(text);
    if (index>=kRussian.size()) return L"";
    return Effective(selected)==Language::English ? kEnglish[index] : kRussian[index];
}

